const byCode = new Map(COUNTRIES.map((c) => [c.code, c]))

export function findCountry(code: string): Country | undefined {
  return byCode.get(code)
}

export function isCountryCode(v: unknown): v is string {
  return typeof v === 'string' && byCode.has(v)
}

// alpha-2 コードから国旗の絵文字を作る（地域指示記号の組み合わせ）
function flagOf(code: string): string {
  return String.fromCodePoint(...[...code].map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65))
}

// 検索用に表記ゆれをそろえる（カタカナ→ひらがな、中黒・空白を除く、英字は小文字）
function normalize(s: string): string {
  return toHiragana(s).replace(/[・\s]/g, '').toLowerCase()
}

const searchTexts = new Map(
  COUNTRIES.map((c) => [c.code, [c.name, c.kana, ...c.aliases].map(normalize)]),
)

const toPlace = (c: Country): Place<string> => ({
  id: c.code,
  name: c.name,
  group: c.continent,
  flag: c.flag ?? flagOf(c.code),
})

// 名前・読み・別名のどこかに入力が含まれる国・地域を返す
// 並び順：完全一致 → 先頭が一致 → 途中に含む（「タイ」で台湾より先にタイが出るように）
export function searchCountries(query: string): Country[] {
  const q = normalize(query.trim())
  if (!q) return COUNTRIES
  const rank = (texts: string[]) =>
    texts.some((t) => t === q) ? 0 : texts.some((t) => t.startsWith(q)) ? 1 : 2
  return COUNTRIES.filter((c) => searchTexts.get(c.code)!.some((t) => t.includes(q)))
    .map((c) => ({ c, r: rank(searchTexts.get(c.code)!) }))
    .sort((a, b) => a.r - b.r)
    .map(({ c }) => c)
}

export const overseasCatalog: PlaceCatalog<string> = {
  placeLabel: '国・地域',
  searchPlaceholder: '国名を入力（例：ふらんす、タイ、米国）',
  groups: CONTINENTS,
  places: COUNTRIES.map(toPlace),
  nameOf: (code) => byCode.get(code)?.name ?? '不明',
  search: (query) => searchCountries(query).map(toPlace),
}
